# 7. Save / reload consistency
# ──────────────────────────────────────────────
class TestSaveReload:
    """Checks track consistency across save and reload."""

    def test_save_and_reload_preserves_tracks(self, board_path: str, krl) -> None:
        """Save then reload the original board: track count and coordinates match."""
        router = krl.RLRouter(board_path)
        output = OUTPUT_DIR / "sample_save_reload.kicad_pcb"

        router.save(str(output))

        router2 = krl.RLRouter(str(output))
        assert router2.get_track_count() == router.get_track_count()

        t1 = router.get_tracks()
        t2 = router2.get_tracks()
        for a, b in zip(t1, t2):
            assert a.x1_mm == pytest.approx(b.x1_mm, abs=0.001)
            assert a.y1_mm == pytest.approx(b.y1_mm, abs=0.001)
            assert a.net_name == b.net_name

    def test_save_after_reroute(self, board_path: str, krl) -> None:
        """Save then reload after a reroute: the changed tracks are reflected."""
        router = krl.RLRouter(board_path)
        _delete_tracks_for_net(router, "NET1")

        router.set_routing_mode(krl.MODE_WALKAROUND)
        router.start_route(1.0, 0.0, LAYER_FCU)
        router.move(1.0, 0.5)
        router.fix_route(1.0, 1.0, force_finish=True)

        count_after = router.get_track_count()
        output = OUTPUT_DIR / "sample_save_after_reroute.kicad_pcb"
        router.save(str(output))

        router2 = krl.RLRouter(str(output))
        assert router2.get_track_count() == count_after


