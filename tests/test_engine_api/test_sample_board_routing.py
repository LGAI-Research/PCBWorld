# 2. Track deletion
# ──────────────────────────────────────────────
class TestTrackDeletion:
    """Checks track deletion."""

    def test_delete_by_index(self, router) -> None:
        before = router.get_track_count()
        assert router.delete_track_by_index(0) is True
        assert router.get_track_count() == before - 1

    def test_delete_by_near(self, router) -> None:
        """Coordinate-based deletion (NET1 F.Cu track)."""
        before = router.get_track_count()
        t = next(
            t for t in router.get_tracks()
            if {(round(t.x1_mm, 3), round(t.y1_mm, 3)),
                (round(t.x2_mm, 3), round(t.y2_mm, 3))} == {(1.0, 0.0), (1.0, 1.0)}
        )
        result = router.delete_track_near(1.0, 0.0, 1.0, 1.0, t.layer, t.net_code, 0.1)
        assert result is True
        assert router.get_track_count() == before - 1

    def test_delete_all_tracks_of_one_net(self, router) -> None:
        """Deletes every track of one net."""
        before = router.get_track_count()
        deleted = _delete_tracks_for_net(router, "NET1")
        assert deleted == 2
        assert router.get_track_count() == before - 2
        assert len(_tracks_for_net(router, "NET1")) == 0

    def test_other_nets_unaffected_after_deletion(self, router) -> None:
        """Other nets are unchanged after deleting one net."""
        _delete_tracks_for_net(router, "NET1")
        net2_tracks = _tracks_for_net(router, "NET2")
        assert len(net2_tracks) == 2


