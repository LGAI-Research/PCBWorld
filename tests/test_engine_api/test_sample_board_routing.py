"""Multi-net / multi-layer routing functional tests using sample_board.

Test board: sample_board.kicad_pcb (generated by generate_sample_board.py)
- K nets, each net k has:
    pads (k, 0) on F.Cu <-> (0, k) on B.Cu
    tracks (k, 0)->(k, k) on F.Cu, (k, k)->(0, k) on B.Cu
    a via at (k, k) F.Cu<->B.Cu
- a polygon obstacle zone on F.Cu: y >= x+5
- trace_width=0.2, via=0.2/0.1, clearance=0.3

Coverage:
  - initial board state (track count, layers, nets, coordinates, width)
  - track deletion (by index, by coordinate)
  - reroute after deletion (F.Cu / B.Cu / multi-net)
  - behavior per routing mode (walkaround, shove, mark_obstacles)
  - save / reload consistency
"""

import sys
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
BUILD_DIR = PROJECT_ROOT / "build_rl"
RL_MODULE_DIR = BUILD_DIR / "pcbnew" / "python" / "rl"
BOARD_PATH = PROJECT_ROOT / "tests" / "fixtures" / "sample_board.kicad_pcb"
OUTPUT_DIR = PROJECT_ROOT / "var" / "tests" / "output"

LAYER_FCU = 0
LAYER_BCU = 2
TRACE_WIDTH = 0.2

sys.path.insert(0, str(RL_MODULE_DIR))


def _import_krl():
    try:
        import kicad_rl_router as krl
        return krl
    except ImportError:
        pytest.skip(f"kicad_rl_router module not found: {RL_MODULE_DIR}")


@pytest.fixture(autouse=True)
def _ensure_output_dir() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


@pytest.fixture
def board_path() -> str:
    if not BOARD_PATH.exists():
        pytest.skip(f"test board not found: {BOARD_PATH}")
    return str(BOARD_PATH)


@pytest.fixture
def krl():
    return _import_krl()


@pytest.fixture
def router(board_path: str, krl):
    return krl.RLRouter(board_path)


def _detect_k(router) -> int:
    """Infers K (the net count) from the board."""
    return router.get_track_count() // 2


def _tracks_for_net(router, net_name: str) -> list:
    return [t for t in router.get_tracks() if t.net_name == net_name]


def _delete_tracks_for_net(router, net_name: str) -> int:
    """Deletes every track of the given net; returns the number deleted."""
    deleted = 0
    while True:
        tracks = router.get_tracks()
        idx = next((i for i, t in enumerate(tracks) if t.net_name == net_name), None)
        if idx is None:
            break
        router.delete_track_by_index(idx)
        deleted += 1
    return deleted


# ──────────────────────────────────────────────
# 1. Board load and initial state
# ──────────────────────────────────────────────
class TestBoardInitialState:
    """Checks the initial state after loading the board."""

    def test_load_success(self, router) -> None:
        assert router is not None

    def test_initial_track_count_is_even(self, router) -> None:
        """K tracks each on F.Cu and B.Cu, so the total is even."""
        assert router.get_track_count() % 2 == 0
        assert router.get_track_count() > 0

    def test_tracks_exist_on_two_layers(self, router) -> None:
        """Tracks are distributed across F.Cu(0) and B.Cu(2)."""
        layers = {t.layer for t in router.get_tracks()}
        assert LAYER_FCU in layers
        assert LAYER_BCU in layers
        assert len(layers) == 2

    def test_net_count_equals_k(self, router) -> None:
        """Unique net count across tracks equals K."""
        k = _detect_k(router)
        nets = {t.net_name for t in router.get_tracks()}
        assert len(nets) == k

    def test_each_net_has_two_tracks(self, router) -> None:
        """Each net has 1 F.Cu + 1 B.Cu track = 2 tracks."""
        k = _detect_k(router)
        for i in range(1, k + 1):
            net_tracks = _tracks_for_net(router, f"NET{i}")
            assert len(net_tracks) == 2, f"NET{i}: expected 2 tracks, got {len(net_tracks)}"

    def test_fcu_segments_are_vertical(self, router) -> None:
        """F.Cu tracks are vertical (x fixed, y varies)."""
        fcu = [t for t in router.get_tracks() if t.layer == LAYER_FCU]
        for t in fcu:
            assert t.x1_mm == pytest.approx(t.x2_mm, abs=0.01), (
                f"F.Cu track not vertical: ({t.x1_mm},{t.y1_mm})->({t.x2_mm},{t.y2_mm})"
            )

    def test_bcu_segments_are_horizontal(self, router) -> None:
        """B.Cu tracks are horizontal (y fixed, x varies)."""
        bcu = [t for t in router.get_tracks() if t.layer == LAYER_BCU]
        for t in bcu:
            assert t.y1_mm == pytest.approx(t.y2_mm, abs=0.01), (
                f"B.Cu track not horizontal: ({t.x1_mm},{t.y1_mm})->({t.x2_mm},{t.y2_mm})"
            )

    def test_track_width(self, router) -> None:
        """Every track's width is 0.2mm."""
        for t in router.get_tracks():
            assert t.width_mm == pytest.approx(TRACE_WIDTH, abs=0.01)

    def test_fcu_track_coordinates(self, router) -> None:
        """F.Cu net k track: (k, 0) -> (k, k)."""
        fcu = [t for t in router.get_tracks() if t.layer == LAYER_FCU]
        for t in fcu:
            k = int(t.net_name.replace("NET", ""))
            assert t.x1_mm == pytest.approx(k, abs=0.01)
            assert t.y1_mm == pytest.approx(0, abs=0.01)
            assert t.x2_mm == pytest.approx(k, abs=0.01)
            assert t.y2_mm == pytest.approx(k, abs=0.01)

    def test_bcu_track_coordinates(self, router) -> None:
        """B.Cu net k track: (k, k) -> (0, k)."""
        bcu = [t for t in router.get_tracks() if t.layer == LAYER_BCU]
        for t in bcu:
            k = int(t.net_name.replace("NET", ""))
            assert t.x1_mm == pytest.approx(k, abs=0.01)
            assert t.y1_mm == pytest.approx(k, abs=0.01)
            assert t.x2_mm == pytest.approx(0, abs=0.01)
            assert t.y2_mm == pytest.approx(k, abs=0.01)


