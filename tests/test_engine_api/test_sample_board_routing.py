# 3. Reroute after deletion (F.Cu)
# ──────────────────────────────────────────────
class TestRerouteFCu:
    """Reroute after deleting the F.Cu segment."""

    def _delete_fcu_track(self, router, net_idx: int) -> None:
        """Deletes only net_idx's F.Cu track."""
        while True:
            tracks = router.get_tracks()
            idx = next(
                (
                    i
                    for i, t in enumerate(tracks)
                    if t.net_name == f"NET{net_idx}" and t.layer == LAYER_FCU
                ),
                None,
            )
            if idx is None:
                break
            router.delete_track_by_index(idx)

    def test_reroute_fcu_direct(self, router, krl) -> None:
        """Reroutes pad->via directly after deleting NET1's F.Cu track."""
        self._delete_fcu_track(router, 1)
        before = router.get_track_count()

        router.set_routing_mode(krl.MODE_WALKAROUND)
        started = router.start_route(1.0, 0.0, LAYER_FCU)
        assert started is True

        router.move(1.0, 0.5)
        success = router.fix_route(1.0, 1.0, force_finish=True)
        assert success is True
        assert router.is_routing() is False
        assert router.get_track_count() > before

    def test_reroute_fcu_with_waypoint(self, router, krl) -> None:
        """Reroutes via a waypoint after deleting NET2's F.Cu track."""
        self._delete_fcu_track(router, 2)
        before = router.get_track_count()

        router.set_routing_mode(krl.MODE_WALKAROUND)
        router.start_route(2.0, 0.0, LAYER_FCU)
        router.move(2.0, 1.0)
        router.fix_route(2.0, 1.0, force_finish=False)
        assert router.is_routing() is True

        success = router.fix_route(2.0, 2.0, force_finish=True)
        assert success is True
        assert router.get_track_count() > before


