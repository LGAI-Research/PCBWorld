# 5. Behavior per routing mode
# ──────────────────────────────────────────────
class TestRoutingModes:
    """Checks reroute behavior for each routing mode."""

    @pytest.mark.parametrize(
        "mode_name,mode_attr",
        [
            ("walkaround", "MODE_WALKAROUND"),
            ("shove", "MODE_SHOVE"),
            ("mark_obstacles", "MODE_MARK_OBSTACLES"),
        ],
    )
    def test_reroute_with_mode(
        self, board_path: str, krl, mode_name: str, mode_attr: str
    ) -> None:
        """Reroute succeeds in each mode after deleting NET1's F.Cu track."""
        router = krl.RLRouter(board_path)
        _delete_tracks_for_net(router, "NET1")

        mode = getattr(krl, mode_attr)
        router.set_routing_mode(mode)

        started = router.start_route(1.0, 0.0, LAYER_FCU)
        assert started, f"start_route failed (mode={mode_name})"

        router.move(1.0, 0.5)
        success = router.fix_route(1.0, 1.0, force_finish=True)
        assert success, f"fix_route failed (mode={mode_name})"
        assert router.get_track_count() > 0


