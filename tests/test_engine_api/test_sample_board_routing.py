# 6. Sequential reroute after deleting multiple nets
# ──────────────────────────────────────────────
class TestMultiNetReroute:
    """Checks sequential reroute after deleting multiple nets."""

    def test_reroute_three_nets_sequentially(self, board_path: str, krl) -> None:
        """Reroutes NET1, NET2, NET3 in order after deleting their F.Cu tracks."""
        router = krl.RLRouter(board_path)
        target_nets = [1, 2, 3]

        for k in target_nets:
            tracks = router.get_tracks()
            idx = next(
                (
                    i
                    for i, t in enumerate(tracks)
                    if t.net_name == f"NET{k}" and t.layer == LAYER_FCU
                ),
                None,
            )
            if idx is not None:
                router.delete_track_by_index(idx)

        for k in target_nets:
            router.set_routing_mode(krl.MODE_WALKAROUND)
            started = router.start_route(float(k), 0.0, LAYER_FCU)
            assert started, f"NET{k} start_route failed"

            router.move(float(k), float(k) * 0.5)
            success = router.fix_route(float(k), float(k), force_finish=True)
            assert success, f"NET{k} fix_route failed"

    def test_cancel_does_not_affect_other_nets(self, board_path: str, krl) -> None:
        """Canceling one net's routing does not affect other nets."""
        router = krl.RLRouter(board_path)
        count_before = router.get_track_count()

        _delete_tracks_for_net(router, "NET1")
        count_after_delete = router.get_track_count()

        router.set_routing_mode(krl.MODE_WALKAROUND)
        router.start_route(1.0, 0.0, LAYER_FCU)
        router.move(1.0, 0.5)
        router.cancel_route()

        assert router.get_track_count() == count_after_delete
        assert router.is_routing() is False

        net2_tracks = _tracks_for_net(router, "NET2")
        assert len(net2_tracks) == 2


