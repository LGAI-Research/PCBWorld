"""Migrate a synthetic dataset to a self-contained `.kicad_pcb` + `.kicad_pro` pair.

The legacy synthetic generator emits only `.kicad_pcb` files with a
KiCad-5 style `(net_class "Default" ...)` block embedded in the board.
KiCad 6+ moves design rules to `.kicad_pro`, and our engine relies on
`copper_edge_clearance`, `hole_to_hole`, etc. — none of which fit in the
legacy block. This script rewrites a dataset so that:

  * every `.kicad_pcb` has the legacy `(net_class ...)` block removed;
  * a sibling `.kicad_pro` carries the full design rules (clearance,
    track_width, via_*, copper_edge_clearance, hole_to_hole, etc.);
  * `KiCadEngine.was_project_loaded_from_file()` returns True on load and
    `was_legacy_design_settings_loaded()` returns False.

Rules are auto-derived from the dataset's own `default_netclass`
(clearance/track_width/via_*) — so any dataset generated by
``generate_synthetic_boards.py`` works without an explicit preset. Pass
``--rules NAME`` to force a hard-coded preset (`RULE_PRESETS` below) when
the source board's netclass values are wrong or missing.

Speedup: all boards in a dataset share the same rules, so we run
`KiCadEngine.save()` once on a single representative board to produce a
template `.kicad_pro`, then bulk-process the rest with text-only ops
(regex strip + filename-field patch). Multiprocessed across CPUs.

Usage:
  python tools/datagen/synthetic_generator/migrate_dataset_to_pro.py \\
      --src pcb_dataset_synthetic_10net_2pin_1layer_grid1000 \\
      --dst pcb_dataset_synthetic_10net_2pin_1layer_grid1000_v2

In-place mode (writes back to the same dir, adding `.kicad_pro` files):
  python tools/datagen/synthetic_generator/migrate_dataset_to_pro.py --src DIR --dst DIR --overwrite
"""
from __future__ import annotations

import argparse
import multiprocessing as mp
import re
import shutil
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))


# Each preset matches a generator config (see scripts/generate_*).
RULE_PRESETS: dict[str, dict[str, float]] = {
    # generate_grid_dataset.sh 1000 (NETS=10, PINS=2, LAYERS=1)
    "1layer_grid1000": dict(
        min_clearance_mm=0.05,
        min_track_width_mm=0.05,
        copper_edge_clearance_mm=0.05,
        min_via_diameter_mm=0.6,
        min_through_hole_mm=0.3,
        min_via_annular_width_mm=0.0,
        min_hole_to_hole_mm=0.0,
        min_uvia_diameter_mm=0.3,
        min_uvia_drill_mm=0.1,
    ),
    # generate_multi_pin_2layer.sh (NETS=5 fixed-pads-per-net 2,2,2,3,4, LAYERS=2)
    "2layer_multi_pin": dict(
        min_clearance_mm=0.3,
        min_track_width_mm=0.3,
        copper_edge_clearance_mm=0.3,
        min_via_diameter_mm=1.2,
        min_through_hole_mm=0.6,
        min_via_annular_width_mm=0.0,
        min_hole_to_hole_mm=0.0,
        min_uvia_diameter_mm=0.3,
        min_uvia_drill_mm=0.1,
    ),
}


# Matches the `(net_class "Default" ...)` block, balancing parens.
def _strip_netclass_block(text: str) -> str:
    start = text.find('(net_class ')
    if start < 0:
        return text
    depth = 0
    i = start
    n = len(text)
    while i < n:
        ch = text[i]
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
            if depth == 0:
                end = i + 1
                trail = end
                while trail < n and text[trail] in ' \t\r\n':
                    trail += 1
                return text[:start].rstrip(' \t') + text[trail:]
        i += 1
    return text


def _derive_rules_from_board(src_pcb: Path, work_dir: Path) -> dict[str, float]:
    """Read the source board's default_netclass and synthesise a rules dict.

    Mirrors the relationship the synthetic generators bake in geometrically:
    ``copper_edge_clearance == clearance``, ``min_through_hole == via_drill``,
    annular/hole_to_hole = 0, microvia = (0.3, 0.1).
    """
    from pcb_world.engine import KiCadEngine
    from pcb_world.engine.utils import load_and_save_via_engine

    work_dir.mkdir(parents=True, exist_ok=True)
    work = work_dir / src_pcb.name
    shutil.copy(src_pcb, work)
    # Source boards are legacy/pro-less — the strict load contract refuses
    # them in KiCadEngine. Normalize the work copy first (raw-router
    # round-trip writes the modern pcb + its .kicad_pro sibling), then open
    # the now-contract-clean pair with the wrapper.
    load_and_save_via_engine(work, work)
    e = KiCadEngine(str(work))
    nc = e.get_design_rules().default_netclass
    rules = dict(
        min_clearance_mm=float(nc.clearance_mm),
        min_track_width_mm=float(nc.track_width_mm),
        copper_edge_clearance_mm=float(nc.clearance_mm),
        min_via_diameter_mm=float(nc.via_diameter_mm),
        min_through_hole_mm=float(nc.via_drill_mm),
        min_via_annular_width_mm=0.0,
        min_hole_to_hole_mm=0.0,
        min_uvia_diameter_mm=0.3,
        min_uvia_drill_mm=0.1,
    )
    e.close()
    return rules


def _build_template(src_pcb: Path, rules: dict[str, float],
                    work_dir: Path) -> tuple[str, str]:
    """Run engine round-trip on one board to extract a template .kicad_pro.

    Returns (template_pro_text, sample_filename_in_template).
    """
    from pcb_world.engine import KiCadEngine
    from pcb_world.engine.utils import load_and_save_via_engine

    work_dir.mkdir(parents=True, exist_ok=True)
    work = work_dir / src_pcb.name
    shutil.copy(src_pcb, work)
    # Same pro-less normalize as _derive_rules_from_board (strict contract).
    load_and_save_via_engine(work, work)
    e = KiCadEngine(str(work))
    r = e.get_design_rules()
    for k, v in rules.items():
        setattr(r, k, v)
    e.set_design_rules(r)
    out = work_dir / "_template.kicad_pcb"
    e.save(str(out))
    e.close()
    pro = out.with_suffix(".kicad_pro")
    pro_text = pro.read_text()
    sample_filename = pro.name  # "_template.kicad_pro"
    return pro_text, sample_filename


_TEMPLATE_PRO: str = ""
_TEMPLATE_FNAME: str = ""


def _worker_init(template_pro: str, template_fname: str) -> None:
    global _TEMPLATE_PRO, _TEMPLATE_FNAME
    _TEMPLATE_PRO = template_pro
    _TEMPLATE_FNAME = template_fname


def _process_one(args: tuple[str, str]) -> tuple[str, bool, str]:
    src_str, dst_str = args
    try:
        src = Path(src_str)
        dst = Path(dst_str)
        text = src.read_text()
        stripped = _strip_netclass_block(text)
        dst.write_text(stripped)
        pro_path = dst.with_suffix(".kicad_pro")
        pro_text = _TEMPLATE_PRO.replace(
            f'"filename": "{_TEMPLATE_FNAME}"',
            f'"filename": "{pro_path.name}"',
        )
        pro_path.write_text(pro_text)
        return (src.name, True, "")
    except Exception as exc:
        return (Path(src_str).name, False, repr(exc))


def _verify_one(dst_pcb: Path, expected: dict[str, float]) -> None:
    """Reload one migrated board and assert rules + flags match."""
    from pcb_world.engine import KiCadEngine
    e = KiCadEngine(str(dst_pcb))
    try:
        assert e.was_project_loaded_from_file(), "kicad_pro not detected"
        assert not e.was_legacy_design_settings_loaded(), "legacy block still present"
        r = e.get_design_rules()
        for k, v in expected.items():
            got = getattr(r, k)
            # KiCad serialiser rounds to nm (1e-6 mm); allow 1e-5 slack.
            assert abs(got - v) < 1e-5, f"{k}: got {got}, expected {v}"
    finally:
        e.close()


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--src", type=Path, required=True,
                   help="source dataset dir (contains board_*.kicad_pcb)")
    p.add_argument("--dst", type=Path, required=True,
                   help="output dir (created; must not exist)")
    p.add_argument("--rules", default=None, choices=sorted(RULE_PRESETS.keys()),
                   help="force a hard-coded preset; default = auto-derive from "
                        "the source board's default_netclass.")
    p.add_argument("--workers", type=int, default=mp.cpu_count())
    p.add_argument("--limit", type=int, default=0,
                   help="if >0, only process this many boards (for smoke testing)")
    p.add_argument("--overwrite", action="store_true",
                   help="allow --dst to already exist")
    args = p.parse_args()

    if not args.src.is_dir():
        raise SystemExit(f"--src not a directory: {args.src}")
    if args.dst.exists() and not args.overwrite:
        raise SystemExit(f"--dst already exists: {args.dst} (use --overwrite)")
    args.dst.mkdir(parents=True, exist_ok=True)

    def _board_idx(p: Path) -> int:
        try:
            return int(p.stem.split("_", 1)[1])
        except Exception:
            return 1 << 31
    files = sorted(args.src.glob("board_*.kicad_pcb"), key=_board_idx)
    if not files:
        raise SystemExit(f"no board_*.kicad_pcb in {args.src}")
    if args.limit > 0:
        files = files[: args.limit]
    print(f"src      : {args.src}  ({len(files)} boards)")
    print(f"dst      : {args.dst}")
    print(f"workers  : {args.workers}")

    work_dir = args.dst / "_template_work"
    if args.rules is not None:
        rules = RULE_PRESETS[args.rules]
        print(f"rules    : preset '{args.rules}'  → {rules}")
    else:
        rules = _derive_rules_from_board(files[0], work_dir)
        print(f"rules    : auto from {files[0].name}  → {rules}")

    print(f"\n[1/3] building template .kicad_pro from {files[0].name} ...")
    t0 = time.time()
    template_pro, template_fname = _build_template(files[0], rules, work_dir)
    print(f"      template ready  ({len(template_pro)} bytes,  {time.time()-t0:.2f}s)")

    print(f"\n[2/3] migrating {len(files)} boards across {args.workers} workers ...")
    tasks = [(str(f), str(args.dst / f.name)) for f in files]
    t0 = time.time()
    fails: list[tuple[str, str]] = []
    with mp.Pool(args.workers, initializer=_worker_init,
                 initargs=(template_pro, template_fname)) as pool:
        done = 0
        for name, ok, err in pool.imap_unordered(_process_one, tasks, chunksize=64):
            done += 1
            if not ok:
                fails.append((name, err))
            if done % 50_000 == 0 or done == len(files):
                print(f"      {done}/{len(files)}  ({done/(time.time()-t0):.0f} boards/s)")
    print(f"      done in {time.time()-t0:.1f}s   failures: {len(fails)}")
    for n, e in fails[:10]:
        print(f"        FAIL {n}: {e}")
    if fails:
        raise SystemExit(1)

    shutil.rmtree(work_dir, ignore_errors=True)

    print("\n[3/3] verifying first/last/middle migrated board ...")
    sample_paths = [args.dst / files[0].name,
                    args.dst / files[len(files) // 2].name,
                    args.dst / files[-1].name]
    for sp in sample_paths:
        _verify_one(sp, rules)
        print(f"      OK {sp.name}")

    n_pcb = len(list(args.dst.glob("board_*.kicad_pcb")))
    n_pro = len(list(args.dst.glob("board_*.kicad_pro")))
    print(f"\nfinal: {n_pcb} pcb + {n_pro} pro in {args.dst}")
    if n_pcb != n_pro or n_pcb != len(files):
        raise SystemExit(f"file count mismatch (expected {len(files)})")


if __name__ == "__main__":
    main()
